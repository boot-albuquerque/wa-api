func TestIsAccessorOperandFormas(t *testing.T) {
	p := &pkgCtx{}
	cases := []struct {
		expr ast.Expr
		want bool
	}{
		{&ast.BasicLit{Kind: token.INT, Value: "1"}, true},
		{&ast.Ident{Name: "x"}, true},
		{&ast.SelectorExpr{X: &ast.Ident{Name: "b"}, Sel: &ast.Ident{Name: "f"}}, true},
		{&ast.SelectorExpr{X: &ast.Ident{Name: "outro"}, Sel: &ast.Ident{Name: "f"}}, false},
		{&ast.SelectorExpr{X: &ast.CallExpr{}, Sel: &ast.Ident{Name: "f"}}, false},
		{&ast.StarExpr{X: &ast.Ident{Name: "x"}}, true},
		{&ast.UnaryExpr{Op: token.AND, X: &ast.Ident{Name: "x"}}, true},
		{&ast.UnaryExpr{Op: token.SUB, X: &ast.Ident{Name: "x"}}, false},
		{&ast.CallExpr{}, false},
	}
	for i, c := range cases {
		if got := isAccessorOperand(p, c.expr, "b"); got != c.want {
			t.Errorf("caso %d: got %v, quero %v", i, got, c.want)
		}
	}
}

