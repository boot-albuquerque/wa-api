// TestMainViaSubprocesso — `main` so' delega para run; o unico jeito honesto de
// cobri-la e' executando o binario de verdade.
func TestMainViaSubprocesso(t *testing.T) {
	if os.Getenv("LOGCOV_SUBPROCESSO") == "1" {
		os.Args = []string{"logcov", "-flag-que-nao-existe"}
		main()
		return
	}
	cmd := exec.Command(os.Args[0], "-test.run=TestMainViaSubprocesso")
	cmd.Env = append(os.Environ(), "LOGCOV_SUBPROCESSO=1")
	err := cmd.Run()
	var exitErr *exec.ExitError
	if !errors.As(err, &exitErr) {
		t.Fatalf("main deveria sair com codigo != 0, deu %v", err)
	}
}

