#!/usr/bin/env bash
# Trava o teto de 300 linhas por arquivo de producao na raiz do pacote
# internal/waclient/ (ADR-0004: o diretorio deixou de ser espelho drift-zero e
# passou a seguir os mesmos pilares do resto do wa-api).
#
# Por que um script e nao um _test.go: internal/waclient/ esta fora de
# TEST_PKGS/COVER_PKGS/LINT_TARGETS no Makefile (ver .logcov-exclude e o
# racional em HOUSEKEEP.md), entao um teste Go dentro do pacote nunca seria
# executado por `make check`. Este gate roda sempre, no mesmo lugar em que
# waclient-license-check e waclient-drift ja rodam.
#
# Escopo: apenas os arquivos .go da RAIZ de internal/waclient/ (Fase A do
# ADR-0004). Subdiretorios (appstate/, binary/, socket/, store/, types/,
# util/) entram nas Fases B/C e ainda nao respeitam o teto.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

DIR="internal/waclient"
MAX_LINES=300

# internals.go e' gerado por internals_generate.go ("GENERATED BY ...; DO NOT
# EDIT"). Pelo mesmo racional que o ADR-0004 usa para proto/, codigo gerado
# fica fora do teto: dividi-lo nao tem valor porque o gerador o recria.
EXCLUDE_GENERATED="internals.go"

fail=0
checked=0

for f in "$DIR"/*.go; do
  base="$(basename "$f")"
  case "$base" in
    *_test.go) continue ;;
    "$EXCLUDE_GENERATED") continue ;;
  esac
  if head -1 "$f" | grep -q "GENERATED BY"; then
    continue
  fi
  checked=$((checked + 1))
  lines="$(wc -l < "$f" | tr -d ' ')"
  if [ "$lines" -gt "$MAX_LINES" ]; then
    echo "FALHA: $f tem $lines linhas (teto $MAX_LINES, ADR-0004)."
    fail=1
  fi
done

if [ "$checked" -eq 0 ]; then
  echo "FALHA: nenhum arquivo .go de producao encontrado em $DIR/ — escopo do gate quebrou."
  exit 1
fi

echo "waclient-filesize-check: $checked arquivos .go de producao na raiz de $DIR/ dentro do teto de $MAX_LINES linhas."

exit "$fail"
